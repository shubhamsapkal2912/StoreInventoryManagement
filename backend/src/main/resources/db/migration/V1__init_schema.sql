CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(255) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    full_name     VARCHAR(120) NOT NULL,
    phone         VARCHAR(30),
    address       VARCHAR(500),
    role          VARCHAR(20)  NOT NULL,
    enabled       BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMPTZ  NOT NULL,
    updated_at    TIMESTAMPTZ  NOT NULL,
    CONSTRAINT chk_users_role CHECK (role IN ('STORE_MANAGER', 'CUSTOMER'))
);
CREATE UNIQUE INDEX uq_users_email ON users (LOWER(email));

CREATE TABLE refresh_tokens (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    token_hash  VARCHAR(64) NOT NULL,
    family_id   VARCHAR(36) NOT NULL,
    expires_at  TIMESTAMPTZ NOT NULL,
    revoked_at  TIMESTAMPTZ,
    created_at  TIMESTAMPTZ NOT NULL,
    CONSTRAINT uq_refresh_tokens_hash UNIQUE (token_hash)
);
CREATE INDEX idx_refresh_tokens_user ON refresh_tokens (user_id);
CREATE INDEX idx_refresh_tokens_family ON refresh_tokens (family_id);

CREATE TABLE categories (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100) NOT NULL,
    description VARCHAR(500),
    created_at  TIMESTAMPTZ  NOT NULL,
    updated_at  TIMESTAMPTZ  NOT NULL
);
CREATE UNIQUE INDEX uq_categories_name ON categories (LOWER(name));

CREATE TABLE products (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name              VARCHAR(200)  NOT NULL,
    sku               VARCHAR(64)   NOT NULL,
    barcode           VARCHAR(64),
    description       VARCHAR(2000),
    category_id       BIGINT REFERENCES categories (id),
    price             NUMERIC(12, 2) NOT NULL,
    cost_price        NUMERIC(12, 2) NOT NULL,
    quantity          INTEGER       NOT NULL DEFAULT 0,
    reorder_threshold INTEGER       NOT NULL DEFAULT 0,
    active            BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at        TIMESTAMPTZ   NOT NULL,
    updated_at        TIMESTAMPTZ   NOT NULL,
    CONSTRAINT uq_products_sku UNIQUE (sku),
    CONSTRAINT uq_products_barcode UNIQUE (barcode),
    CONSTRAINT chk_products_quantity CHECK (quantity >= 0),
    CONSTRAINT chk_products_threshold CHECK (reorder_threshold >= 0),
    CONSTRAINT chk_products_price CHECK (price >= 0 AND cost_price >= 0)
);
CREATE INDEX idx_products_name ON products (LOWER(name));
CREATE INDEX idx_products_category ON products (category_id);
CREATE INDEX idx_products_active ON products (active);

CREATE TABLE inventory_movements (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id      BIGINT      NOT NULL REFERENCES products (id),
    type            VARCHAR(20) NOT NULL,
    quantity_change INTEGER     NOT NULL,
    quantity_after  INTEGER     NOT NULL,
    reason          VARCHAR(500),
    reference       VARCHAR(100),
    created_by      BIGINT REFERENCES users (id),
    created_at      TIMESTAMPTZ NOT NULL,
    CONSTRAINT chk_movement_type CHECK (type IN ('STOCK_IN', 'STOCK_OUT', 'ADJUSTMENT', 'ORDER_PLACED', 'ORDER_CANCELLED', 'INITIAL')),
    CONSTRAINT chk_movement_after CHECK (quantity_after >= 0)
);
CREATE INDEX idx_movements_product ON inventory_movements (product_id);
CREATE INDEX idx_movements_created ON inventory_movements (created_at);

CREATE TABLE cart_items (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    product_id BIGINT      NOT NULL REFERENCES products (id),
    quantity   INTEGER     NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uq_cart_user_product UNIQUE (user_id, product_id),
    CONSTRAINT chk_cart_quantity CHECK (quantity > 0)
);

CREATE TABLE orders (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id      BIGINT         NOT NULL REFERENCES users (id),
    status           VARCHAR(20)    NOT NULL,
    total_amount     NUMERIC(14, 2) NOT NULL,
    shipping_address VARCHAR(500)   NOT NULL,
    notes            VARCHAR(1000),
    created_at       TIMESTAMPTZ    NOT NULL,
    updated_at       TIMESTAMPTZ    NOT NULL,
    CONSTRAINT chk_order_status CHECK (status IN ('PLACED', 'CONFIRMED', 'PROCESSING', 'SHIPPED', 'DELIVERED', 'CANCELLED'))
);
CREATE INDEX idx_orders_customer ON orders (customer_id);
CREATE INDEX idx_orders_status ON orders (status);
CREATE INDEX idx_orders_created ON orders (created_at);

CREATE TABLE order_items (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id     BIGINT         NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
    product_id   BIGINT         NOT NULL REFERENCES products (id),
    product_name VARCHAR(200)   NOT NULL,
    sku          VARCHAR(64)    NOT NULL,
    unit_price   NUMERIC(12, 2) NOT NULL,
    quantity     INTEGER        NOT NULL,
    line_total   NUMERIC(14, 2) NOT NULL,
    CONSTRAINT chk_order_item_qty CHECK (quantity > 0)
);
CREATE INDEX idx_order_items_order ON order_items (order_id);
CREATE INDEX idx_order_items_product ON order_items (product_id);
